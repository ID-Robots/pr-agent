"""Per-repository extra_instructions from the categories of the reference findings humans fixed.

    python -m tools.review_eval.repo_instructions --dataset .eval-data/dev.jsonl \\
        --out .eval-data/repo_instructions.toml

For every repository, the references labelled `addressed` are counted by category and severity, and
the counts become a short text that asks the reviewer to look for the most often fixed kinds of
defect first. Only category names, severity names and counts are used: no comment body, file name or
other text of the dataset reaches the output. The output is a TOML file keyed by the repository's
short name; it names the dataset's repositories, so it must stay in a git-ignored folder.

The harness adds a repository's text to pr_reviewer.extra_instructions and
pr_code_suggestions.extra_instructions when the profile sets `[review_eval] repo_instructions = true`
and `--repo-instructions PATH` names this file.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import tomllib
from collections import Counter, defaultdict
from pathlib import Path

from tools.review_eval.dataset import PullRequestEntry, load_dataset

INSTRUCTION_KEYS = ("pr_reviewer.extra_instructions", "pr_code_suggestions.extra_instructions")
TOP_CATEGORIES = 5
_SEVERITY_ORDER = ("critical", "major", "minor", "trivial")
_LABEL_MAX_CHARS = 40


def _label(value: str) -> str:
    """A category or severity as a short plain label: lower case letters, digits and single spaces."""
    words = re.sub(r"[^a-z0-9]+", " ", str(value).lower()).split()
    return " ".join(words)[:_LABEL_MAX_CHARS].strip()


def _severity_rank(name: str) -> tuple[int, str]:
    return (_SEVERITY_ORDER.index(name) if name in _SEVERITY_ORDER else len(_SEVERITY_ORDER), name)


def instructions_text(categories: Counter, severities: Counter, fixed: int) -> str:
    """The extra_instructions text for one repository's counts of fixed (addressed) references."""
    parts = [f"In earlier reviews of this repository, developers fixed {fixed} reported "
             f"finding{'s' if fixed != 1 else ''}."]
    top = sorted(categories.items(), key=lambda item: (-item[1], item[0]))[:TOP_CATEGORIES]
    if top:
        parts.append("The kinds fixed most often: " + ", ".join(f"{name} ({count})" for name, count in top) + ".")
    if severities:
        ranked = sorted(severities.items(), key=lambda item: _severity_rank(item[0]))
        parts.append("By severity: " + ", ".join(f"{count} {name.capitalize()}" for name, count in ranked) + ".")
    parts.append("Look for these kinds of defect first, and report each one with its file and line.")
    return " ".join(parts)


def build_instructions(entries: list[PullRequestEntry]) -> dict[str, str]:
    """Map each repository short name to its text; a repository without addressed references is left out."""
    full_names: dict[str, str] = {}
    fixed: Counter = Counter()
    categories: dict[str, Counter] = defaultdict(Counter)
    severities: dict[str, Counter] = defaultdict(Counter)
    for entry in entries:
        other = full_names.setdefault(entry.name, entry.full_name)
        if other.lower() != entry.full_name.lower():
            raise ValueError(f"repositories {other} and {entry.full_name} share the short name {entry.name}")
        for reference in entry.references:
            if not reference.addressed:
                continue
            fixed[entry.name] += 1
            category, severity = _label(reference.category), _label(reference.severity)
            if category:
                categories[entry.name][category] += 1
            if severity:
                severities[entry.name][severity] += 1
    return {name: instructions_text(categories[name], severities[name], fixed[name]) for name in sorted(fixed)}


def render_toml(instructions: dict[str, str], dataset_name: str) -> str:
    lines = [f"# Generated by python -m tools.review_eval.repo_instructions from {dataset_name}.",
             "# It names the dataset's repositories: keep it in a git-ignored folder and never commit it.", ""]
    for name, text in instructions.items():
        # A JSON string is a valid TOML basic string.
        lines += [f"[{json.dumps(name)}]", f"extra_instructions = {json.dumps(text)}", ""]
    return "\n".join(lines)


def load_repo_instructions(path: str | Path) -> dict[str, str]:
    """Read a generated file: repository short name -> extra_instructions text."""
    with open(path, "rb") as handle:
        data = tomllib.load(handle)
    instructions = {}
    for name, table in data.items():
        text = table.get("extra_instructions") if isinstance(table, dict) else None
        if not isinstance(text, str) or not text.strip():
            raise ValueError(f"{Path(path).name}: table [{name}] needs a non-empty extra_instructions string")
        instructions[name] = text.strip()
    return instructions


def unit_settings(instructions: dict[str, str], entry: PullRequestEntry, profile_settings: dict) -> dict:
    """The extra_instructions settings for one entry: the profile's own text, then the repository's."""
    text = instructions.get(entry.name)
    if not text:
        return {}
    settings = {}
    for key in INSTRUCTION_KEYS:
        own = str(profile_settings.get(key) or "").strip()
        settings[key] = f"{own}\n\n{text}" if own else text
    return settings


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(
        prog="python -m tools.review_eval.repo_instructions",
        description="Write per-repository extra_instructions from the categories of the addressed references.")
    parser.add_argument("--dataset", required=True, type=Path, help="JSONL dataset (generate from the dev set only)")
    parser.add_argument("--out", required=True, type=Path, help="output TOML, in a git-ignored folder")
    args = parser.parse_args(argv)
    # Imported here: the CLI module imports this one.
    from tools.review_eval.cli import check_output_dir

    def fail(message: str) -> int:
        print(f"repo_instructions: {message}", file=sys.stderr)
        return 2

    if not args.dataset.is_file():
        return fail(f"dataset not found: {args.dataset}")
    problem = check_output_dir(args.out.parent)
    if problem:
        return fail(problem)
    try:
        instructions = build_instructions(load_dataset(args.dataset))
    except (OSError, ValueError) as error:
        return fail(str(error))
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(render_toml(instructions, args.dataset.name), encoding="utf-8")
    print(f"repo_instructions: wrote instructions for {len(instructions)} "
          f"repositor{'y' if len(instructions) == 1 else 'ies'} to {args.out}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
